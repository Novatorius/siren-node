#!/usr/bin/env node
/*
 * Rebuild the catalog fixtures in test/fixtures/ from a Siren checkout.
 *
 * Usage: node scripts/siren-fixtures.mjs <path-to-siren-checkout> [--check]
 *
 * It reads the PHP source that builds each answer and writes the body the
 * controller would serve:
 *
 * - webhook-events.json: `GET /webhooks/events`, which serves
 *   `WebhookCatalog::all()`, one `{ event, category, label }` per entry of
 *   `WebhookCatalog::EVENTS`, in order.
 * - api-key-scopes.json: `GET /api-keys/scopes`, which serves
 *   `ApiKeyScopePolicy::issuableGroups()`: the `events` group first, then each
 *   `ApiKeyRecordScopes` resource in the order `DEFINITIONS` first names it.
 *   The `events` group holds the scopes `RegisterCoreApiKeyScopes` registers
 *   with `addEventScope`, in order. An organization's custom event types add
 *   more at run time, and the fixture holds none.
 *
 * With `--check`, it writes nothing and exits 1 when a committed fixture
 * differs from what the source gives, so a stale fixture is caught.
 */
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const [sirenPath, flag] = process.argv.slice(2);
if (!sirenPath) {
  console.error('usage: node scripts/siren-fixtures.mjs <path-to-siren-checkout> [--check]');
  process.exit(2);
}
const check = flag === '--check';
const fixtures = resolve(process.cwd(), 'test/fixtures');

function php(relative) {
  return readFileSync(resolve(sirenPath, relative), 'utf8');
}

// A PHP single-quoted string: backslash escapes only `\'` and `\\`.
const STR = "'((?:[^'\\\\]|\\\\.)*)'";
function unquote(text) {
  return text.replace(/\\(['\\])/g, '$1');
}

function block(source, name) {
  const start = source.indexOf(`const ${name} = [`);
  if (start < 0) throw new Error(`const ${name} not found`);
  const end = source.indexOf('\n    ];', start);
  if (end < 0) throw new Error(`end of const ${name} not found`);
  return source.slice(start, end);
}

function constants(source) {
  const map = new Map();
  for (const match of source.matchAll(new RegExp(`const ([A-Z_]+) = ${STR};`, 'g'))) {
    map.set(match[1], unquote(match[2]));
  }
  return map;
}

function constant(map, name, file) {
  if (!map.has(name)) throw new Error(`${file}: constant ${name} not found`);
  return map.get(name);
}

function webhookEvents() {
  const file = 'lib/Webhooks/Service/Services/WebhookCatalog.php';
  const events = block(php(file), 'EVENTS');
  const entries = [...events.matchAll(new RegExp(`${STR} => \\[${STR}, ${STR}\\]`, 'g'))];
  if (entries.length === 0) throw new Error(`${file}: no events found`);
  return entries.map((m) => ({ event: unquote(m[1]), category: unquote(m[2]), label: unquote(m[3]) }));
}

function apiKeyScopes() {
  const recordFile = 'lib/ApiKeys/Core/Enums/ApiKeyRecordScopes.php';
  const recordSource = php(recordFile);
  const recordConstants = constants(recordSource);
  const definitions = block(recordSource, 'DEFINITIONS');
  const pattern = new RegExp(
    `self::([A-Z_]+) => \\['resource' => self::([A-Z_]+), 'action' => ${STR}, 'label' => ${STR}\\]`,
    'g',
  );
  const records = [...definitions.matchAll(pattern)].map((m) => ({
    scope: constant(recordConstants, m[1], recordFile),
    resource: constant(recordConstants, m[2], recordFile),
    action: unquote(m[3]),
    label: unquote(m[4]),
  }));
  if (records.length === 0) throw new Error(`${recordFile}: no definitions found`);

  const coreFile = 'lib/ApiKeys/Core/Listeners/RegisterCoreApiKeyScopes.php';
  const forwardedFile = 'lib/EventForwarding/Core/Enums/ForwardedEventSlug.php';
  const forwarded = constants(php(forwardedFile));
  const eventPattern = new RegExp(`addEventScope\\((?:${STR}|ForwardedEventSlug::([A-Z_]+)), ${STR}\\)`, 'g');
  const events = [...php(coreFile).matchAll(eventPattern)].map((m) => {
    const slug = m[1] !== undefined ? unquote(m[1]) : constant(forwarded, m[2], forwardedFile);
    return { scope: `event:${slug}`, resource: 'events', action: slug, label: unquote(m[3]) };
  });
  if (events.length === 0) throw new Error(`${coreFile}: no event scopes found`);

  const groups = { events };
  for (const entry of records) {
    (groups[entry.resource] ??= []).push(entry);
  }
  return groups;
}

const commit = execFileSync('git', ['-C', sirenPath, 'rev-parse', '--short', 'HEAD'], { encoding: 'utf8' }).trim();
const outputs = {
  'webhook-events.json': {
    _source: `Siren ${commit}, generated by scripts/siren-fixtures.mjs from lib/Webhooks/Service/Services/WebhookCatalog.php, as GET /webhooks/events serves it (WebhookCatalog::all)`,
    body: webhookEvents(),
  },
  'api-key-scopes.json': {
    _source: `Siren ${commit}, generated by scripts/siren-fixtures.mjs as GET /api-keys/scopes serves it (ApiKeyScopePolicy::issuableGroups): event scopes from lib/ApiKeys/Core/Listeners/RegisterCoreApiKeyScopes.php, then lib/ApiKeys/Core/Enums/ApiKeyRecordScopes.php DEFINITIONS. No custom event types.`,
    body: apiKeyScopes(),
  },
};

let stale = 0;
for (const [name, content] of Object.entries(outputs)) {
  const path = resolve(fixtures, name);
  const text = `${JSON.stringify(content, null, 2)}\n`;
  if (check) {
    const current = readFileSync(path, 'utf8');
    const same = JSON.stringify(JSON.parse(current).body) === JSON.stringify(content.body);
    console.log(`${same ? 'OK   ' : 'STALE'} ${name}`);
    if (!same) stale += 1;
  } else {
    writeFileSync(path, text);
    console.log(`wrote ${name}`);
  }
}
process.exit(stale === 0 ? 0 : 1);
