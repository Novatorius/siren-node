#!/usr/bin/env node
/*
 * Write src/feature-kind.ts from src/app-kinds.json, Siren's
 * docs/api/app-kinds.json copied byte for byte (scripts/siren-fixtures.mjs
 * copies it). Each FeatureKind member gets a doc comment with the kind's
 * name, its term where the term differs, Siren's description of it, and
 * whether Siren tells, asks or receives it, so an editor shows them on hover.
 *
 * Usage: node scripts/feature-kind.mjs [--check]
 *
 * With `--check`, it writes nothing and exits 1 when src/feature-kind.ts
 * differs from what the snapshot gives. test/feature-kind.test.ts runs it.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const snapshotPath = resolve(root, 'src/app-kinds.json');
const outputPath = resolve(root, 'src/feature-kind.ts');

const MODES = {
  tell: 'A tell: Siren lets the app know, and the app answers nothing.',
  ask: 'An ask: Siren waits for the app to answer.',
  receive: "Siren receives it: the app sends it to Siren with `events.ingest()`, and Siren never sends one.",
};

/** The words, wrapped to lines that fit in 80 columns after `prefix`. */
function wrap(text, prefix) {
  const lines = [];
  let line = '';
  for (const word of text.split(/\s+/)) {
    if (line !== '' && prefix.length + line.length + 1 + word.length > 80) {
      lines.push(`${prefix}${line}`);
      line = word;
    } else {
      line = line === '' ? word : `${line} ${word}`;
    }
  }
  if (line !== '') lines.push(`${prefix}${line}`);
  return lines;
}

export function render(entries) {
  const out = [
    '// Generated by scripts/feature-kind.mjs from src/app-kinds.json. Do not edit.',
    '// Copy a new snapshot with scripts/siren-fixtures.mjs, then run the generator.',
    '',
    '/**',
    ...wrap(
      "The kinds of feature an app may add, as Siren registers them (AppItemKindCatalog::catalog(), served by `GET /apps/kinds`), in the order Siren's \"New feature\" chooser lists them. The kind is the id Siren sends in `request.feature.kind` and stores. The name is what Siren's screens show. A record selects a feature by `app:{id}`.",
      ' * ',
    ),
    ' */',
    'export const FeatureKind = {',
  ];
  for (const entry of entries) {
    const member = entry.kind.charAt(0).toUpperCase() + entry.kind.slice(1);
    const termDiffers = entry.term.toLowerCase() !== entry.name.toLowerCase();
    out.push('  /**');
    out.push(`   * ${entry.name}.${termDiffers ? ` Siren's code calls it the ${entry.term}.` : ''}`);
    out.push('   *');
    out.push(...wrap(entry.description, '   * '));
    out.push('   *');
    out.push(...wrap(MODES[entry.mode], '   * '));
    out.push('   */');
    out.push(`  ${member}: '${entry.kind}',`);
  }
  out.push('} as const;', '', '/** Union of the {@link FeatureKind} strings. */', 'export type FeatureKind = (typeof FeatureKind)[keyof typeof FeatureKind];', '');
  return out.join('\n');
}

const entries = JSON.parse(readFileSync(snapshotPath, 'utf8'));
const text = render(entries);
if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(outputPath, 'utf8');
  } catch {
    current = '';
  }
  if (current === text) {
    console.log('OK    src/feature-kind.ts');
  } else {
    console.log('STALE src/feature-kind.ts: run node scripts/feature-kind.mjs');
    process.exit(1);
  }
} else {
  writeFileSync(outputPath, text);
  console.log('wrote src/feature-kind.ts');
}
